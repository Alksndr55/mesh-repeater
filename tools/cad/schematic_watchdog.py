"""ATtiny13A reset watchdog adapted from the user's watchdog project."""
from schematic_core import Sheet

def build():
    s=Sheet('Watchdog','ATtiny13A — внешний watchdog из пользовательского проекта',5)
    s.sym('U6',101.6,80.01)
    s.sym('C33',35.56,57.15,'C_V')
    s.sym('R36',60.96,66.04,'R_V')
    s.sym('R37',147.32,67.31,'R_H')
    s.sym('R33',173.99,52.07,'R_V')
    s.sym('R38',35.56,92.71,'R_H')
    s.sym('R39',60.96,107.95,'R_V')
    # One supply, parallel local decoupling; own reset is separate from MCU_RESET.
    s.wire((35.56,43.18),(76.2,43.18),(76.2,67.31),('U6',8))
    s.global_stub('SYS_3V3',(35.56,43.18),(25.4,43.18))
    s.wire(('C33',1),(35.56,43.18));s.ground(('C33',2),2.54)
    s.wire(('R36',1),(60.96,43.18));s.dot((60.96,43.18))
    s.wire(('R36',2),(60.96,80.01),('U6',1))
    s.global_stub('WDT_RESET',(60.96,80.01),(50.8,80.01))
    s.wire(('R38',2),('U6',2));s.net('R38',1,5.08)
    s.wire(('R39',1),(60.96,92.71));s.dot((60.96,92.71))
    s.ground(('R39',2),2.54);s.ground(('U6',4),2.54)
    s.wire(('U6',5),('R37',1))
    s.wire((127.0,67.31),(127.0,35.56));s.dot((127.0,67.31))
    s.global_stub('WDT_MOSI_RESET',(127.0,35.56),(132.08,35.56),angle=180)
    s.wire(('R37',2),(190.5,67.31))
    s.label('MCU_RESET',(190.5,67.31),180,True)
    s.wire(('R33',2),(173.99,67.31));s.dot((173.99,67.31))
    s.net('R33',1,5.08)
    s.net('U6',6,10.16);s.net('U6',7,10.16);s.nc('U6',3)
    s.sym('J10',220.98,86.36,label=(220.98,64.77,220.98,67.31))
    for pin in range(1,7):s.net('J10',pin,5.08)
    s.text('TXEN HT-RA62 → R38 → PB3 (вывод 2). Контроль появления передач.',15.24,137.16,1.15)
    s.text('Нет импульсов TXEN: 1350 тактов WDT по 8 с ≈ 3 ч; затем RESET ≈ 1 с.',15.24,144.78,1.15)
    s.text('PB0 (вывод 5): только LOW или Hi-Z. RESET ATtiny (вывод 1) — отдельная цепь.',15.24,152.4,1.15)
    s.text('J10: стандартный AVR ISP, уровни 3,3 В; SCK ≤ 10 кГц после установки fuse.',15.24,160.02,1.15)
    s.text('Плата питается сама: питание цели от программатора отключить. Для ISP снять R37.',15.24,167.64,1.15)
    s.text('Сначала FLASH, затем LFUSE=0x7B / HFUSE=0xFB: 128 кГц, SUT ≈64 мс, BOD 2,7 В.',15.24,175.26,1.15)
    s.text('Прошивка: watchdog/main.c. Штатное молчание радио более ≈3 ч также вызовет сброс.',15.24,182.88,1.15)
    s.text('BOD следит за SYS_3V3; порог EN батареи не меняется. Проверить восстановление и ток сна.',15.24,190.5,1.15)
    return s
